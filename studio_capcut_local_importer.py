def make_draft(*,drafts_dir,allow_subtitles=False,open_app=False):
    try:
        import pycapcut as cc
    except ImportError:
        raise RuntimeError(
            "Biblioteca pyCapCut não instalada. Execute no terminal: "
            "python -m pip install pycapcut==0.0.4")
    info,scenes=read_package()
    base,voice,captions=find_media_in_package()
    if not base:
        raise RuntimeError(
            "Para manter a linha do tempo inteira mesmo sem os B-rolls antigos, "
            "este pacote precisa incluir 03_midias_locais/video_final_base.mp4. "
            "Baixe novamente pelo Estúdio IA.")
    if not voice:
        raise RuntimeError("A narração separada não foi encontrada no pacote")
    drafts_dir=Path(drafts_dir).expanduser()
    if not drafts_dir.is_dir():
        raise RuntimeError(
            "Pasta de rascunhos não encontrada: "+str(drafts_dir)+
            ". Verifique CapCut > Configurações > Local dos rascunhos.")
    project_label=safe_filename(info.get("project_title") or "Video")
    project_id=safe_filename(str(info.get("project_id") or "")[:8])
    draft_name="Estudio IA - "+project_label+" - "+project_id+" - "+str(uuid.uuid4())[:6]

    folder=cc.DraftFolder(str(drafts_dir))
    duration=min(7200.,max(1.,float(scenes[-1]["fim_s"])))
    # 16:9 to match the generated narration/captions and CapCut preview.
    aspect=str(info.get("ratio") or "16:9")
    w,h=(960,540) if aspect=="16:9" else (540,960)
    script=folder.create_draft(draft_name,w,h,30,maintrack_adsorb=False)
    script.add_track(cc.TrackType.video, "Video base")
    script.add_track(cc.TrackType.video, "B-rolls editaveis",relative_index=2)
    script.add_track(cc.TrackType.audio, "Narracao")
    used=0
    overlay_count=0
    # Original complete export is a safe placeholder. Each shot becomes an
    # independent editable clip from the corresponding time in that export.
    # Its embedded captions/music are not magically restored as raw elements.
    for scene in scenes:
        start=float(scene["inicio_s"])
        end=float(scene["fim_s"])
        target=cc.trange_seconds(start,end=end)
        source=cc.trange_seconds(start,end=end)
        clip=cc.VideoSegment(str(base),target,source_timerange=source,
                             volume=0.0)
        script.add_segment(clip,"Video base")
        used+=1
        rel=scene.get("arquivo_local_no_zip") or ""
        local=valid_entry(rel)
        if not local or local.suffix.lower() not in VIDEO_EXT or local==base:
            continue
        try:
            material=cc.VideoMaterial(str(local))
            source_seconds=float(material.duration)/cc.SEC
            clip_seconds=min(end-start,source_seconds)
            if clip_seconds<.75:
                continue
            broll=cc.VideoSegment(
                str(local),cc.trange_seconds(start,duration=clip_seconds),
                source_timerange=cc.trange_seconds(0,duration=clip_seconds),
                volume=0.0)
            script.add_segment(broll,"B-rolls editaveis")
            overlay_count+=1
        except (OSError,ValueError,RuntimeError):
            # Archive contains some 3rd party formats not understood by the
            # local editor; retain safe base fallback for that scene.
            continue
    narration=cc.AudioMaterial(str(voice))
    length=min(duration,float(narration.duration)/cc.SEC)
    if length<3:
        raise RuntimeError("A narração não contém duração suficiente")
    script.add_segment(
        cc.AudioSegment(str(voice),cc.trange_seconds(0,duration=length)),
        "Narracao")
    captions_added=False
    # The video base already contains burned captions. Optional import
    # creates editable SRT captions but they will overlay the baked ones.
    if allow_subtitles and captions:
        script.import_srt(str(captions),track_name="Legendas editaveis")
        captions_added=True
    script.save()
    print("\nRASCUNHO CRIADO COM SUCESSO")
    print("Nome:",draft_name)
    print("Pasta:",drafts_dir)
    print("Cenas cortadas no video base:",used)
    print("B-rolls separados adicionados:",overlay_count)
    print("Narração em trilha própria:",bool(voice))
    print("Legendas editáveis:",captions_added)
    print("\nIMPORTANTE: algumas tomadas usam a versão final cortada porque")
    print("os B-rolls antigos não estavam armazenados separadamente.")
    print("Não apague ou mova a pasta extraída do ZIP, pois contém as mídias.")
    print("Abra o CapCut Desktop; se necessário, reinicie para ver o rascunho.")
    if open_app:
        try:
            import subprocess
            if sys.platform=="darwin":
                subprocess.Popen(["open","-a","CapCut"],stdout=subprocess.DEVNULL,
                                 stderr=subprocess.DEVNULL)
            elif sys.platform=="win32":
                os.startfile(str(drafts_dir)) # Show where the new draft lives
        except (OSError,ValueError):
            pass
    return draft_name

def main():
    parser=argparse.ArgumentParser(
        description="Criar novo rascunho do CapCut Desktop a partir do pacote do Estúdio IA")
    parser.add_argument("--drafts-dir",default=os.getenv("CAPCUT_DRAFTS_DIR") or "")
    parser.add_argument("--subtitles",action="store_true",
                        help="Criar trilha de SRT editável (pode duplicar as legendas embutidas)")
    parser.add_argument("--open",action="store_true",help="Abrir CapCut (macOS) ou sua pasta (Windows)")
    parser.add_argument("--check",action="store_true",help="Só verificar conteúdo, sem instalar")
    args=parser.parse_args()
    info,scenes=read_package()
    base,voice,captions=find_media_in_package()
    print("Estúdio IA:",info.get("project_title"),"-",len(scenes),"cenas")
    print("Vídeo de referência:",bool(base),"narração:",bool(voice),
          "SRT:",bool(captions))
    if args.check:return
    drafts=Path(args.drafts_dir) if args.drafts_dir else default_drafts()
    if not drafts:raise RuntimeError("Importação automática requer CapCut Desktop no Windows ou macOS")
    make_draft(drafts_dir=drafts,allow_subtitles=args.subtitles,open_app=args.open)

if __name__=="__main__":
    try:
        main()
    except (RuntimeError,ValueError,OSError,KeyError) as exc:
        print("\nERRO:",str(exc),file=sys.stderr)
        sys.exit(1)
