"""Experimental local importer for Meu Estúdio IA -> CapCut Desktop.

Run on the computer that has CapCut Desktop. Creates a NEW draft in the
CapCut drafts directory, never overwrites any existing project. Works from
the self-contained downloaded ZIP generated by estudio-video.

This uses community-maintained pyCapCut (pin 0.0.4), NOT an official CapCut
file API. Compatibility varies by CapCut version and is not guaranteed.
The app must be closed while writing drafts, then restarted to find the draft.

Missing B-roll is replaced with trimmed pieces of the *already rendered* MP4.
That allows timing edits but not reconstruction of missing original footage.
"""
from __future__ import annotations
import argparse
import csv
import json
import os
import platform
import re
import shutil
import sys
import uuid
from pathlib import Path

ROOT=Path(__file__).resolve().parent
VIDEO_EXT={".mp4",".mov",".webm",".mkv"}
AUDIO_EXT={".mp3",".m4a",".wav",".aac"}
IMAGE_EXT={".png",".jpg",".jpeg",".webp"}
DRAFT_DIR="com.lveditor.draft"

def default_drafts():
    if sys.platform=="win32":
        base=os.environ.get("LOCALAPPDATA","")
        if not base:
            return None
        return Path(base)/"CapCut"/"User Data"/"Projects"/DRAFT_DIR
    if sys.platform=="darwin":
        return Path.home()/"Movies"/"CapCut"/"User Data"/"Projects"/DRAFT_DIR
    return None

def safe_filename(value):
    cleaned=re.sub(r'[<>:"/\\|?*\r\n\t]'," ",str(value or ""))
    return " ".join(cleaned.split())[:58]

def valid_entry(value):
    s=str(value or "").strip()
    if not s or "\\" in s or s.startswith("/") or ".." in Path(s).parts:
        return None
    rel=Path(s)
    candidate=(ROOT/rel).resolve()
    if not candidate.is_relative_to(ROOT) or candidate.is_symlink() or not candidate.is_file():
        return None
    return candidate

def read_package():
    info=ROOT/"04_plano"/"manifesto.json"
    table=ROOT/"04_plano"/"ordem_cenas.csv"
    if not info.is_file() or not table.is_file():
        raise RuntimeError("Pacote inválido: manifesto e ordem de cenas não encontrados")
    metadata=json.loads(info.read_text(encoding="utf-8"))
    if metadata.get("version")!="capcut-handoff-v1":
        raise RuntimeError("Pacote com versão desconhecida")
    with table.open("r",encoding="utf-8-sig",newline="") as handle:
        scenes=list(csv.DictReader(handle))
    if not scenes or len(scenes)>120:
        raise RuntimeError("Quantidade de cenas não suportada")
    for i,scene in enumerate(scenes,1):
        if int(scene.get("cena") or 0)!=i:
            raise RuntimeError("Numeração das cenas fora de ordem")
        start=float(scene["inicio_s"]);end=float(scene["fim_s"])
        if not 0<=start<end<=7200:
            raise RuntimeError("Tempo inválido na cena "+str(i))
    return metadata,scenes

def find_media_in_package():
    base=valid_entry("03_midias_locais/video_final_base.mp4")
    audios=ROOT/"01_audio"
    narration=None
    for ext in AUDIO_EXT:
        possibility=valid_entry("01_audio/narracao_completa"+ext)
        if possibility:
            narration=possibility;break
    captions=valid_entry("02_legendas/legendas.srt") or valid_entry("02_legendas/subtitles.srt")
    return base,narration,captions

